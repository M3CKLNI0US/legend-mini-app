const DICT = { ru: RU, en: EN, zh: ZH }

/**
 * @param {string} lang
 * @param {string} key
 */
export function translate(lang, key) {
  const L = DICT[lang] || DICT.ru
  return L[key] ?? DICT.ru[key] ?? key
}

export function normalizeLang(lang) {
  if (lang === 'en' || lang === 'zh') return lang
  return 'ru'
}
